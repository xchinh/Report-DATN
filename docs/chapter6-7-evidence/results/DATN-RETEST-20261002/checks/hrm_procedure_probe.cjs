const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const root = process.env.HRM_REPO;
if (!root || !process.env.TEST_STAFF_SHCC) throw new Error('Set HRM_REPO and TEST_STAFF_SHCC from the approved account matrix');
const localRequire = createRequire(path.join(root, 'package.json'));
const { Client } = localRequire('pg');
const env = localRequire('dotenv').parse(fs.readFileSync(path.join(root, '.env.local')));

// Exercise the deployed function, using session-local tables and ROLLBACK.
// No public workflow row or public sequence is modified; this is not mobile E2E.
(async () => {
    const db = new Client({ host: env.PG_HOST, port: Number(env.PG_PORT), database: env.PG_DATABASE,
        user: env.PG_USERNAME || env.PG_USER, password: env.PG_PASSWORD });
    await db.connect();
    try {
        await db.query('BEGIN');
        await db.query('SET LOCAL search_path = pg_temp, public');
        await db.query('CREATE TEMP TABLE tcns_nghi_phep_dang_ky (LIKE public.tcns_nghi_phep_dang_ky) ON COMMIT DROP');
        await db.query('CREATE TEMP TABLE tcns_nghi_phep (LIKE public.tcns_nghi_phep) ON COMMIT DROP');
        await db.query('ALTER TABLE pg_temp.tcns_nghi_phep ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY');
        const seed = await db.query('INSERT INTO pg_temp.tcns_nghi_phep_dang_ky SELECT * FROM public.tcns_nghi_phep_dang_ky WHERE shcc=$1 ORDER BY id DESC LIMIT 1 RETURNING id', [process.env.TEST_STAFF_SHCC]);
        assert.equal(seed.rowCount, 1, 'Approved staff needs one existing request as read-only seed');
        const namespace = await db.query("SELECT n.nspname FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE c.oid='tcns_nghi_phep'::regclass");
        assert.match(namespace.rows[0].nspname, /^pg_temp_/, 'Abort unless the target resolves to a session-local table');
        for (const cursor of ['probe_one', 'probe_two']) {
            await db.query('SELECT public.tcns_nghi_phep_dang_ky_insert($1::refcursor, $2::integer)', [cursor, seed.rows[0].id]);
            await db.query(`CLOSE ${cursor}`);
        }
        const result = await db.query('SELECT count(*)::integer AS rows, count(DISTINCT phieu_id)::integer AS requests FROM pg_temp.tcns_nghi_phep');
        assert.deepEqual(result.rows[0], { rows: 2, requests: 1 });
        console.log(JSON.stringify({ check: 'H02', function_calls: 2, leave_rows: 2, distinct_requests: 1,
            storage: 'session-local TEMP tables', cleanup: 'ROLLBACK', result: 'duplicate insert reproduced' }));
    } finally {
        await db.query('ROLLBACK');
        await db.end();
    }
})().catch(error => { console.error('Probe failed:', error.code || error.name); process.exitCode = 1; });
